"""Hash the runtime files used by the CHOG loader and service worker."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parent.parent
files = []
for path in sorted(ROOT.iterdir()):
    if path.is_file() and path.suffix in {'.html', '.css', '.js'} and path.name != 'precache.js':
        files.append(path)
for path in sorted((ROOT / 'assets').rglob('*')):
    if not path.is_file() or path.suffix.lower() not in {'.webp', '.png', '.svg', '.mp3', '.ogg', '.js', '.ttf', '.woff2'}:
        continue
    relative = path.relative_to(ROOT).as_posix()
    if '/source-art/' in relative:
        continue
    files.append(path)
for path in sorted((ROOT / 'online').rglob('*')):
    if path.is_file() and path.suffix in {'.mjs', '.js', '.css', '.json', '.txt'}:
        files.append(path)
entries = [[p.relative_to(ROOT).as_posix(), p.stat().st_size,
            hashlib.sha1(p.read_bytes()).hexdigest()[:12]] for p in files]
version = hashlib.sha1(json.dumps(entries).encode()).hexdigest()[:12]
result = dict(version=version, total=sum(p[1] for p in entries), files=entries)
(ROOT / 'precache.js').write_text('/* Generated by tools/build_cache.py. */\nself.CHOG_PRECACHE = '
                                + json.dumps(result, separators=(',', ':')) + ';\n')
deployment=[dict(file=p[0],bytes=p[1]) for p in entries]
deployment.append(dict(file='precache.js',bytes=(ROOT/'precache.js').stat().st_size))
for notice in ['LICENSE','THIRD_PARTY_NOTICES.md','assets/chog/landing/fonts/bangers-OFL.txt','assets/chog/landing/fonts/barlow-OFL.txt']:
    deployment.append(dict(file=notice,bytes=(ROOT/notice).stat().st_size))
(ROOT/'files.json').write_text(json.dumps(dict(files=len(deployment),bytes=sum(p['bytes'] for p in deployment),list=deployment),indent=2)+'\n')
print(f'{len(entries)} runtime files, {result["total"] / 1e6:.1f} MB, version {version}')
